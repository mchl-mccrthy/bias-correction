% Make scatter plot of Theil-Sen slopes
function plottrendcomparison(station_theil_sen_slopes,...
    raw_station_theil_sen_slopes,bc_station_theil_sen_slopes,...
    file_path_figures_tables,clim_var_name,clim_var_long_name,clim_var_units,...
    agg_method)

% Get trend units
trend_units = trendunits(clim_var_units,agg_method);

% Make plot
figure()
data_lims = [min([station_theil_sen_slopes raw_station_theil_sen_slopes ...
    bc_station_theil_sen_slopes 0]), ...
        max([station_theil_sen_slopes raw_station_theil_sen_slopes ...
        bc_station_theil_sen_slopes 0])];
lims = paddedequallims(data_lims(1),data_lims(2));
plot(lims,lims,'k:','HandleVisibility','off'); hold on
scatter(station_theil_sen_slopes,raw_station_theil_sen_slopes,10,'filled',...
    'MarkerFaceColor',[0.45 0.45 0.45],...
    'MarkerEdgeColor',[0.45 0.45 0.45])
scatter(station_theil_sen_slopes,bc_station_theil_sen_slopes,10,'filled',...
    'MarkerFaceColor','r','MarkerEdgeColor','r')
xlabel([clim_var_long_name ' trend, stations (' ...
    trend_units ')'])
ylabel([clim_var_long_name ' trend, gridded (' ...
    trend_units ')'])
title('All stations, trends')
xlim(lims)
ylim(lims)
tick_values = linspace(lims(1),lims(2),5);
xticks(tick_values)
yticks(tick_values)
legend('Raw','Bias-corrected','Location','eastoutside')
formatfigure(gcf,4,4,4)
print(gcf,fullfile(file_path_figures_tables,[clim_var_name ...
    '_trends_scatter.png']),'-dpng','-r300');

end
